export const readerCatalogues: Readonly<Record<ReaderLocale, Readonly<Catalogue>>> = { en, de, es, fr, it, 'pt-BR': ptBR };
export function readerLocale(value: string): ReaderLocale {
  return Object.hasOwn(readerCatalogues, value) ? value as ReaderLocale : 'en';
}
export const formatCount = (value: number, locale: string, options?: Intl.NumberFormatOptions) => new Intl.NumberFormat(readerLocale(locale), options).format(value);
type Placeholders<S extends string> = S extends `${string}{${infer Param}}${infer Rest}` ? Param | Placeholders<Rest> : never;
export type TranslationParams<K extends TranslationKey> = Record<Placeholders<typeof en[K]>, string | number>;
type Arguments<K extends TranslationKey> = [Placeholders<typeof en[K]>] extends [never] ? [] : [params: TranslationParams<K>];
export type Translator = <K extends TranslationKey>(key: K, ...args: Arguments<K>) => string;
function interpolate(locale: ReaderLocale, key: TranslationKey, params: Record<string, string | number> = {}): string {
  const text = readerCatalogues[locale][key];
  if (typeof text !== 'string') throw new Error(`Missing reader translation: ${locale}.${key}`);
  const names = [...text.matchAll(/\{(\w+)\}/g)].map(match => match[1]);
  if (names.some(name => !Object.hasOwn(params, name)) || Object.keys(params).some(name => !names.includes(name))) throw new Error(`Invalid reader interpolation: ${locale}.${key}`);
  return text.replace(/\{(\w+)\}/g, (_, name: string) => typeof params[name] === 'number' ? formatCount(params[name], locale) : params[name] as string);
}
export function translator(locale: string): Translator {
  const selected = readerLocale(locale);
  // Known locales have complete dictionaries: missing keys are errors, never English fallbacks.
  return ((key: TranslationKey, params?: Record<string, string | number>) => interpolate(selected, key, params)) as Translator;
}

/** Display known application messages in the reader locale, without rewriting
 * arbitrary supplier diagnostics, source wording, or persisted evidence. */
const applicationMessages = Object.entries(en).map(([key, text]) => ({ key: key as TranslationKey, text }));
export function readerMessage(message: string, locale: string): string {
  const selected = readerLocale(locale);
  const exact = applicationMessages.find(entry => entry.text === message && !/\{\w+\}/.test(entry.text));
  if (exact) return interpolate(selected, exact.key);
  for (const key of ['cloudLoadFailed', 'cloudSaveFailed', 'clearFailed', 'sourceLimit', 'xSourceLimit', 'archiveRejected', 'archiveLoadFailed', 'archiveRetryFailed'] as const) {
    const template = en[key];
    const name = template.includes('{count}') ? 'count' : 'detail';
    const [start, end] = template.split(`{${name}}`);
    if (message.startsWith(start) && message.endsWith(end)) {
      const value = message.slice(start.length, end ? -end.length : undefined);
      if (!value || (name === 'count' && !/^\d+$/.test(value))) continue;
      return interpolate(selected, key, { [name]: name === 'count' ? Number(value) : value });
    }
  }
  return message;
}
