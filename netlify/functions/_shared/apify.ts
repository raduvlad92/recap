export interface ApifyConfig { token: string; secret: string; build: string; maxItems: number; maxCharge: number; allowedUsers: string[] }
export function apifyConfig(env: Env): ApifyConfig | null {
  const token = env('APIFY_API_TOKEN'), secret = env('COLLECTION_JOB_SECRET'), build = env('APIFY_YOUTUBE_BUILD');
  const maxItems = Number(env('APIFY_MAX_ITEMS') || '3'), maxCharge = Number(env('APIFY_MAX_TOTAL_CHARGE_USD'));
  const allowedUsers = (env('COLLECTION_ALLOWED_USER_IDS') || '').split(',').map((id) => id.trim()).filter(Boolean);
  if (env('APIFY_RUNTIME_ENABLED') !== 'true' || !token || !secret || secret.length < 32 || !build || !/^\d+\.\d+\.\d+$/.test(build) ||
    !Number.isInteger(maxItems) || maxItems < 1 || maxItems > 5 || !(maxCharge > 0 && maxCharge <= 0.1) || !allowedUsers.length) return null;
  return { token, secret, build, maxItems, maxCharge, allowedUsers };
}

function requireConfig(env: Env, userId: string): ApifyConfig {
  const config = apifyConfig(env);
  if (!config) throw new CollectionError(503, 'provider_not_configured', 'YouTube collection is not enabled yet. Public feed collection is available after sign-in.');
  if (!config.allowedUsers.includes(userId)) throw new CollectionError(403, 'collection_not_allowed', 'Paid collection is restricted to the configured operator in this version.');
  return config;
}

export function youtubeInput(source: Source, maxItems: number): Record<string, unknown> {
  const url = publicHttpsUrl(source.url);
  if (!['www.youtube.com', 'youtube.com', 'm.youtube.com', 'youtu.be'].includes(url.hostname)) {
    throw new CollectionError(400, 'platform_mismatch', 'Use a public YouTube channel or video link.');
  }
  if (url.hostname === 'youtu.be') {
    if (!/^\/[A-Za-z0-9_-]{11}$/.test(url.pathname)) throw new CollectionError(400, 'unsupported_youtube_url', 'Use a channel link or one public video link.');
  } else if (!( /^\/@[^/]+(?:\/videos)?\/?$/.test(url.pathname) || /^\/channel\/UC[A-Za-z0-9_-]+(?:\/videos)?\/?$/.test(url.pathname) ||
    (url.pathname === '/watch' && /^[A-Za-z0-9_-]{11}$/.test(url.searchParams.get('v') || '')) || /^\/shorts\/[A-Za-z0-9_-]{11}$/.test(url.pathname))) {
    throw new CollectionError(400, 'unsupported_youtube_url', 'Use a public YouTube channel or video link. Search and playlist scraping are not enabled.');
  }
  for (const key of [...url.searchParams.keys()]) if (key !== 'v') url.searchParams.delete(key);
  return {
    startUrls: [{ url: url.href }], maxResults: maxItems, maxResultsShorts: 0, maxResultStreams: 0,
    sortVideosBy: 'NEWEST', transcriptionAndSubtitle: 'ALWAYS_SUBTITLES', subtitlesLanguage: 'any', subtitlesFormat: 'srt',
    saveSubsToKVS: false, preferAutoGeneratedSubtitles: false, aiVideoDescription: false, aiVideoSummary: false,
  };
}

type Fetcher = typeof fetch;
async function apifyRequest(path: string, config: Pick<ApifyConfig, 'token'>, fetcher: Fetcher, init: RequestInit = {}, capture?: (text: string) => void): Promise<unknown> {
  const response = await fetchNoRedirect('https://api.apify.com/v2/' + path, {
    ...init, signal: AbortSignal.timeout(12_000),
    headers: { authorization: 'Bearer ' + config.token, 'content-type': 'application/json', ...init.headers },
  }, fetcher);
  if (!response.ok) {
    await response.body?.cancel();
    throw new CollectionError(502, 'provider_error', 'The collection provider did not accept this request. No automatic retry was started.');
  }
  const text = await readTextLimited(response, 2 * 1024 * 1024);
  capture?.(text);
  try { return JSON.parse(text); } catch { throw new CollectionError(502, 'provider_response_invalid', 'The collection provider returned an unreadable response.'); }
}

const stableJson = (value: unknown): string => Array.isArray(value) ? '[' + value.map(stableJson).join(',') + ']'
  : value && typeof value === 'object' ? '{' + Object.keys(value).sort().map(key => JSON.stringify(key) + ':' + stableJson((value as Record<string, unknown>)[key])).join(',') + '}' : JSON.stringify(value) ?? 'null';

/** Free provider metadata only; call BEFORE claiming a paid launch reservation. */
export async function verifyHourlyApifyConfiguration(userId: string, env: Env, fetcher: Fetcher = fetch): Promise<void> {
  const config = requireConfig(env, userId), buildId = env('APIFY_YOUTUBE_BUILD_ID'), pricingHash = env('APIFY_YOUTUBE_PRICING_SHA256');
  if (env('HOURLY_COLLECTION_PROVIDER_VERIFIED') !== 'true' || config.maxItems !== 1 || config.maxCharge > 0.005 || !buildId || !/^[a-f0-9]{64}$/.test(pricingHash || '')) {
    throw new CollectionError(503, 'provider_review_required', 'The bounded collector needs a reviewed build and price before it can run.');
  }
  const [actorResponse, buildResponse] = await Promise.all([
    apifyRequest('acts/' + YOUTUBE_ACTOR, config, fetcher), apifyRequest('actor-builds/' + providerId(buildId), config, fetcher),
  ]);
  const actor = object(object(actorResponse).data), build = object(object(buildResponse).data);
  const prices = Array.isArray(actor.pricingInfos) ? actor.pricingInfos : [];
  const currentPricing = prices.filter(value => {
    const started = object(value).startedAt;
    return typeof started === 'string' && Date.parse(started) <= Date.now();
  }).sort((a, b) => String(object(a).startedAt).localeCompare(String(object(b).startedAt))).at(-1);
  if (actor.id !== YOUTUBE_ACTOR_ID || build.id !== buildId || build.actId !== YOUTUBE_ACTOR_ID || build.status !== 'SUCCEEDED' || build.buildNumber !== config.build ||
    !currentPricing || createHash('sha256').update(stableJson(currentPricing)).digest('hex') !== pricingHash) {
    throw new CollectionError(503, 'provider_review_changed', 'The collector build or price changed. Paid pulls are paused for review.');
  }
}

function object(value: unknown): Record<string, unknown> {
  return value && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : {};
}
function providerId(value: unknown): string {
  if (typeof value !== 'string' || !/^[A-Za-z0-9]{6,64}$/.test(value)) throw new CollectionError(502, 'provider_response_invalid', 'The collection provider returned an invalid job reference.');
  return value;
}

export interface ApifyFeeEvidence {
  run_id: string; actor_id: string; build_id: string; status: string;
  finished_at: string | null; observed_at: string; response_sha256: string;
  usage_usd: string | null; maximum_usd: string; authenticated_owner: true;
}

// Preserve the original JSON decimal token. Never round through a JS number.
// Duplicate/nested same-name fields are ambiguous and fail closed.
function moneyToken(text: string, key: string, parsed: unknown): string | null {
  const tokens = [...text.matchAll(new RegExp('"' + key + '"\\s*:\\s*(null|-?(?:0|[1-9]\\d*)(?:\\.\\d+)?(?:[eE][+-]?\\d+)?)(?=\\s*[,}])', 'g'))];
  if (tokens.length !== 1) throw new CollectionError(502, 'provider_fee_invalid', 'Exact provider money is unavailable.');
  const raw = tokens[0][1];
  if (raw === 'null' && parsed === null) return null;
  if (typeof parsed !== 'number' || !Number.isFinite(parsed) || parsed < 0 || Number(raw) !== parsed || raw.length > 80 || !/^(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][+-]?\d{1,2})?$/.test(raw)) {
    throw new CollectionError(502, 'provider_fee_invalid', 'Exact provider money is unavailable.');
  }
  return raw;
}

/** GET-only, server-owned saved identity. No launch flag, dataset or source read. */
export async function readApifyFeeEvidence(job: { userId: string; providerRunId: string; actorId: string }, env: Env, fetcher: Fetcher = fetch): Promise<ApifyFeeEvidence> {
  const token = env('APIFY_API_TOKEN'), build = env('APIFY_YOUTUBE_BUILD_ID');
  if (!token || !build || job.actorId !== YOUTUBE_ACTOR_ID || !(env('COLLECTION_ALLOWED_USER_IDS') || '').split(',').map(s => s.trim()).includes(job.userId)) {
    throw new CollectionError(403, 'provider_fee_not_authorized', 'Provider fee inspection is restricted to the configured operator.');
  }
  const id = providerId(job.providerRunId); let raw = '';
  const response = object(await apifyRequest('actor-runs/' + id, { token }, fetcher, {}, text => { raw = text; }));
  const observedAt = new Date().toISOString();
  const run = object(response.data), me = object(object(await apifyRequest('users/me', { token }, fetcher)).data);
  if (run.id !== id || run.actId !== job.actorId || run.buildId !== build || typeof me.id !== 'string' || run.userId !== me.id) {
    throw new CollectionError(409, 'provider_fee_identity_changed', 'Provider run, build or authenticated owner does not match.');
  }
  if (!['READY','RUNNING','TIMING-OUT','ABORTING','SUCCEEDED','FAILED','TIMED-OUT','ABORTED'].includes(String(run.status))) {
    throw new CollectionError(502, 'provider_fee_invalid', 'Provider run status is unavailable.');
  }
  const maximum = moneyToken(raw, 'maxTotalChargeUsd', object(run.options).maxTotalChargeUsd);
  if (maximum === null) throw new CollectionError(502, 'provider_fee_invalid', 'Provider run cap is unavailable.');
  return { run_id: id, actor_id: job.actorId, build_id: build, status: String(run.status),
    finished_at: typeof run.finishedAt === 'string' && Number.isFinite(Date.parse(run.finishedAt)) ? new Date(run.finishedAt).toISOString() : null,
    usage_usd: run.usageTotalUsd === undefined ? null : moneyToken(raw, 'usageTotalUsd', run.usageTotalUsd), maximum_usd: maximum,
    observed_at: observedAt, response_sha256: createHash('sha256').update(raw).digest('hex'), authenticated_owner: true };
}

export async function startApify(source: Source, userId: string, env: Env, fetcher: Fetcher = fetch, ledgerId?: string): Promise<{ status: 'running'; jobToken: string; message: string; providerRunId: string }> {
  const config = requireConfig(env, userId);
  const input = youtubeInput(source, config.maxItems);
  const params = new URLSearchParams({ build: config.build, timeout: '120', maxItems: String(config.maxItems), maxTotalChargeUsd: String(config.maxCharge), restartOnError: 'false', waitForFinish: '0' });
  const response = object(await apifyRequest('actors/' + YOUTUBE_ACTOR + '/runs?' + params, config, fetcher, { method: 'POST', body: JSON.stringify(input) }));
  const run = object(response.data);
  const runId = providerId(run.id), actorId = providerId(run.actId);
  const jobToken = await new SignJWT({ runId, actorId, source, maxItems: config.maxItems, ...(ledgerId ? {ledgerId} : {}) })
    .setProtectedHeader({ alg: 'HS256', typ: 'JWT' }).setSubject(userId).setIssuer('therecap-collection').setAudience('collection-job')
    .setIssuedAt().setExpirationTime('20m').sign(new TextEncoder().encode(config.secret));
  return { status: 'running', jobToken, providerRunId: runId, message: 'Collecting up to ' + config.maxItems + ' recent videos and available captions. Missing captions will remain metadata only.' };
}

/** Channel discovery is a separate paid scope, never a caption-job identity. */
export async function startYouTubeDiscovery(source: Source, channelId: string, userId: string, env: Env, fetcher: Fetcher = fetch): Promise<{ providerRunId: string }> {
  const config = requireConfig(env, userId);
  if (!/^UC[A-Za-z0-9_-]{22}$/.test(channelId)) throw new CollectionError(400, 'invalid_job', 'Stable channel identity required.');
  const input = youtubeInput({ ...source, url: 'https://www.youtube.com/channel/' + channelId }, DISCOVERY_ITEMS);
  const params = new URLSearchParams({ build: config.build, timeout: '120', maxItems: String(DISCOVERY_ITEMS), maxTotalChargeUsd: String(DISCOVERY_MAX_USD), restartOnError: 'false', waitForFinish: '0' });
  const run = object(object(await apifyRequest('acts/' + YOUTUBE_ACTOR + '/runs?' + params, config, fetcher, { method: 'POST', body: JSON.stringify(input) })).data);
  if (run.actId !== YOUTUBE_ACTOR_ID || run.buildId !== env('APIFY_YOUTUBE_BUILD_ID')) throw new CollectionError(502, 'provider_build_mismatch', 'The discovery run did not match its reviewed build.');
  return { providerRunId: providerId(run.id) };
}

export function captionsText(value: unknown): string {
  if (!Array.isArray(value)) return '';
  for (const entry of value) {
    const subtitle = object(entry);
    // Only inline subtitle text is consumed. No provider-supplied URL is fetched.
    if (typeof subtitle.srt !== 'string') continue;
    const text = subtitle.srt.replace(/^\s*\d+\s*$/gm, '').replace(/^.*-->.*$/gm, '').replace(/^WEBVTT.*$/gm, '');
    const result = plainText(text, 200_000);
    if (result) return result;
  }
  return '';
}

export function normalizeYouTubeItems(items: unknown, source: Source, maxItems = 5): SourceUpdate[] {
  if (!Array.isArray(items)) throw new CollectionError(502, 'provider_response_invalid', 'The collection provider returned an invalid dataset.');
  const updates = new Map<string, SourceUpdate>();
  for (const item of items) {
    const row = object(item);
    if (row.isMembersOnly === true || row.isPrivate === true) continue;
    const url = safeLink(row.url, 'https://www.youtube.com');
    if (!url || !['youtube.com', 'www.youtube.com', 'm.youtube.com', 'youtu.be'].includes(new URL(url).hostname) || updates.has(url)) continue;
    const transcript = captionsText(row.subtitles), description = plainText(row.text, 700);
    const rawCaption = Array.isArray(row.subtitles) ? row.subtitles.map(object).find(entry => typeof entry.srt === 'string' && plainText(entry.srt))?.srt : undefined;
    const transcriptSegments = typeof rawCaption === 'string' ? parseTimedTranscript(rawCaption).slice(0, 10_000) : [];
    const date = typeof row.date === 'string' ? Date.parse(row.date) : NaN;
    const refs = Array.isArray(row.descriptionLinks) ? row.descriptionLinks : [];
    updates.set(url, {
      id: 'live-' + createHash('sha256').update(source.id + '\n' + url).digest('hex').slice(0, 24), sourceId: source.id, contributorIds: [],
      title: plainText(row.title, 240) || 'Untitled video', summary: transcript ? transcript.slice(0, 700) : description,
      ...(transcript ? { content: transcript, contentKind: 'transcript' as const, ...(transcriptSegments.length ? { transcriptSegments } : {}) } : { contentKind: 'metadata_only' as const }),
      url, publishedAt: Number.isFinite(date) ? new Date(date).toISOString() : '', format: 'video', topics: [], brands: [], sponsors: [],
      references: refs.slice(0, 10).flatMap((value) => {
        const ref = object(value), link = safeLink(ref.url, url);
        return link ? [{ title: plainText(ref.text, 160) || new URL(link).hostname, url: link }] : [];
      }),
      insights: [], ...(typeof row.duration === 'string' ? { duration: plainText(row.duration, 30) } : {}),
      ...(typeof row.isShort === 'boolean' ? { isShort: row.isShort } : typeof row.isShorts === 'boolean' ? { isShort: row.isShorts } : {}), ...videoFormatFields(classifyProviderVideoFormat(row, url)),
      ...(safeLink(row.thumbnailUrl, url) ? { image: safeLink(row.thumbnailUrl, url) } : {}), isSample: false,
      coverage: transcript ? 'Existing captions collected; visual content and transcript completeness not verified' + (transcript.length >= 200_000 ? '; source text clipped at 200,000 characters' : '') : 'Metadata only: video description; captions unavailable; video content not analyzed',
    });
    if (updates.size >= Math.min(maxItems, 5)) break;
  }
  return [...updates.values()];
}

export interface ApifyPollResult { status: string; message?: string; result?: CollectionResult; contentError?: string; telemetry?: {ledgerId: string; providerRunId: string; cost: number | null} }
export interface StoredApifyJob { providerRunId: string; actorId: string; source: Source; maxItems: number; ledgerId: string; feeOnly?: boolean; discoveryChannelId?: string }

/** Server-only recovery: input must come from the private provider-job table, never a browser body. */
export async function pollStoredApify(job: StoredApifyJob, userId: string, env: Env, fetcher: Fetcher = fetch): Promise<ApifyPollResult> {
  const config = requireConfig(env, userId);
  if (!job || job.actorId !== YOUTUBE_ACTOR_ID || !/^[0-9a-f-]{36}$/i.test(job.ledgerId) || job.maxItems !== (job.discoveryChannelId ? DISCOVERY_ITEMS : 1) || job.source?.platform !== 'YouTube') {
    throw new CollectionError(403, 'invalid_job', 'The stored collection job could not be verified.');
  }
  if (job.discoveryChannelId) {
    if (!/^UC[A-Za-z0-9_-]{22}$/.test(job.discoveryChannelId) || job.source.url !== 'https://www.youtube.com/channel/' + job.discoveryChannelId) throw new CollectionError(403, 'invalid_job', 'Discovery channel identity changed.');
    return readApifyRun(providerId(job.providerRunId), providerId(job.actorId), job.source, DISCOVERY_ITEMS, job.ledgerId, config, fetcher, env('APIFY_YOUTUBE_BUILD_ID'), true, job.feeOnly === true, job.discoveryChannelId);
  }
  const input = youtubeInput(job.source, 1);
  const target = new URL((input.startUrls as Array<{url: string}>)[0].url);
  if (!(target.pathname === '/watch' || target.hostname === 'youtu.be' || target.pathname.startsWith('/shorts/'))) {
    throw new CollectionError(403, 'invalid_job', 'Stored jobs must identify one video.');
  }
  return readApifyRun(providerId(job.providerRunId), providerId(job.actorId), job.source, 1, job.ledgerId, config, fetcher, env('APIFY_YOUTUBE_BUILD_ID'), true, job.feeOnly === true);
}

export async function pollApify(jobToken: string, userId: string, env: Env, fetcher: Fetcher = fetch): Promise<ApifyPollResult> {
  const config = requireConfig(env, userId);
  if (!jobToken || jobToken.length > 8000) throw new CollectionError(400, 'invalid_job', 'This collection job is missing or invalid.');
  let claims;
  try {
    claims = (await jwtVerify(jobToken, new TextEncoder().encode(config.secret), { algorithms: ['HS256'], issuer: 'therecap-collection', audience: 'collection-job', requiredClaims: ['sub', 'iat', 'exp'] })).payload;
  } catch { throw new CollectionError(403, 'invalid_job', 'This collection job expired or could not be verified.'); }
  if (claims.sub !== userId) throw new CollectionError(403, 'job_owner_mismatch', 'This collection job belongs to a different account.');
  const runId = providerId(claims.runId), actorId = providerId(claims.actorId);
  const source = object(claims.source) as unknown as Source;
  if (source.platform !== 'YouTube' || typeof source.id !== 'string' || !source.url) throw new CollectionError(403, 'invalid_job', 'This job has invalid source details.');
  const maxItems = Math.min(config.maxItems, Number(claims.maxItems) || 1, 5);
  const ledgerId = typeof claims.ledgerId === 'string' && /^[0-9a-f-]{36}$/i.test(claims.ledgerId) ? claims.ledgerId : undefined;
  return readApifyRun(runId, actorId, source, maxItems, ledgerId, config, fetcher);
}

async function readApifyRun(runId: string, actorId: string, source: Source, maxItems: number, ledgerId: string | undefined, config: ApifyConfig, fetcher: Fetcher, expectedBuildId?: string, preserveTerminalTelemetry = false, feeOnly = false, discoveryChannelId?: string): Promise<ApifyPollResult> {
  const response = object(await apifyRequest('actor-runs/' + runId, config, fetcher));
  const run = object(response.data);
  if (run.id !== runId || run.actId !== actorId) throw new CollectionError(403, 'invalid_job', 'The provider job does not match this request.');
  if (expectedBuildId && run.buildId !== expectedBuildId) throw new CollectionError(403, 'provider_build_mismatch', 'The provider returned an unreviewed build.');
  const telemetry = ledgerId ? { ledgerId, providerRunId: runId, cost: typeof run.usageTotalUsd === 'number' && Number.isFinite(run.usageTotalUsd) && run.usageTotalUsd >= 0 ? run.usageTotalUsd : null } : undefined;
  if (['READY', 'RUNNING', 'TIMING-OUT', 'ABORTING'].includes(String(run.status))) return { status: 'running', message: 'Collection is still running.',telemetry };
  if (!['SUCCEEDED','FAILED','TIMED-OUT','ABORTED'].includes(String(run.status))) throw new CollectionError(502, 'provider_response_invalid', 'The provider returned an unknown run status.');
  if (run.status !== 'SUCCEEDED') return { status: 'failed', message: 'The provider job stopped without a complete result. No automatic retry was started.',telemetry };
  if (feeOnly) return { status: 'completed', telemetry };
  try {
    const datasetId = providerId(run.defaultDatasetId);
    // A three-upload discovery result can exceed the response limit while
    // every complete record fits. Read those fixed offsets separately, keeping
    // all fields and the same per-response byte limit. Empty cleaned rows do
    // not hide later offsets; a failed page still rejects the whole import.
    let items: unknown;
    if (discoveryChannelId) {
      const rows: unknown[] = [];
      for (let offset = 0; offset < DISCOVERY_ITEMS; offset++) {
        const page = await apifyRequest('datasets/' + datasetId + '/items?clean=true&format=json&limit=1&offset=' + offset, config, fetcher);
        if (!Array.isArray(page) || page.length > 1) throw new CollectionError(502, 'provider_response_invalid', 'The provider returned an invalid discovery page.');
        rows.push(...page);
      }
      items = rows;
    } else items = await apifyRequest('datasets/' + datasetId + '/items?clean=true&format=json&limit=' + maxItems, config, fetcher);
    if (discoveryChannelId) {
      if (!Array.isArray(items) || items.some(value => {
        const row = object(value), channelUrl = typeof row.channelUrl === 'string' ? row.channelUrl.replace(/\/$/, '') : '';
        return row.channelId !== discoveryChannelId && channelUrl !== 'https://www.youtube.com/channel/' + discoveryChannelId
          || row.channelId && row.channelId !== discoveryChannelId;
      })) throw new CollectionError(502, 'provider_channel_unconfirmed', 'The returned uploads could not be attributed to the requested channel.');
      if (items.some(value => !exactPublicationTimestamp(object(value).date))) throw new CollectionError(502, 'provider_date_unconfirmed', 'The provider did not supply an exact publication date.');
      if (items.some(value => {
        const row = object(value), videoId = youtubeVideoId(row.url);
        return !videoId || [row.id, row.videoId].some(id => id !== undefined && id !== videoId);
      })) throw new CollectionError(502, 'provider_video_unconfirmed', 'The returned upload did not identify one matching video.');
    }
    const updates = normalizeYouTubeItems(items, source, maxItems);
    if (discoveryChannelId && updates.some(update => !update.publishedAt)) throw new CollectionError(502, 'provider_date_unconfirmed', 'The provider did not supply an exact publication date.');
    return { status: 'completed', telemetry, result: { source: { ...source, status: 'ready' }, updates, notice: 'Collected a bounded recent sample, not a complete channel history. Text is extracted source material, not an AI recap. Descriptions are not video-content coverage.' } };
  } catch (error) {
    if (!preserveTerminalTelemetry) throw error;
    return { status: 'completed', telemetry, contentError: error instanceof CollectionError ? error.code : 'provider_result_unreadable', message: 'The provider finished; its original result remains unread and has not been imported.' };
  }
}
