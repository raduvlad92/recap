import { createHash } from 'node:crypto';
import { SignJWT, jwtVerify } from 'jose';
import type { CollectionResult, Source, SourceUpdate } from '../../../src/lib/types';
import { plainText, safeLink } from './feed';
import { CollectionError, type Env, publicHttpsUrl, readTextLimited } from './security';

export const YOUTUBE_ACTOR = 'streamers~youtube-scraper';
export interface ApifyConfig { token: string; secret: string; build: string; maxItems: number; maxCharge: number; allowedUsers: string[] }
export function apifyConfig(env: Env): ApifyConfig | null {
  const token = env('APIFY_API_TOKEN'), secret = env('COLLECTION_JOB_SECRET'), build = env('APIFY_YOUTUBE_BUILD');
  const maxItems = Number(env('APIFY_MAX_ITEMS') || '3'), maxCharge = Number(env('APIFY_MAX_TOTAL_CHARGE_USD'));
  const allowedUsers = (env('COLLECTION_ALLOWED_USER_IDS') || '').split(',').map((id) => id.trim()).filter(Boolean);
  if (env('APIFY_RUNTIME_ENABLED') !== 'true' || !token || !secret || secret.length < 32 || !build || !/^\d+\.\d+\.\d+$/.test(build) ||
    !Number.isInteger(maxItems) || maxItems < 1 || maxItems > 5 || !(maxCharge > 0 && maxCharge <= 0.1) || !allowedUsers.length) return null;
  return { token, secret, build, maxItems, maxCharge, allowedUsers };
}

function requireConfig(env: Env, userId: string): ApifyConfig {
  const config = apifyConfig(env);
  if (!config) throw new CollectionError(503, 'provider_not_configured', 'YouTube collection is not enabled yet. Public feed collection is available after sign-in.');
  if (!config.allowedUsers.includes(userId)) throw new CollectionError(403, 'collection_not_allowed', 'Paid collection is restricted to the configured operator in this version.');
  return config;
}

export function youtubeInput(source: Source, maxItems: number): Record<string, unknown> {
  const url = publicHttpsUrl(source.url);
  if (!['www.youtube.com', 'youtube.com', 'm.youtube.com', 'youtu.be'].includes(url.hostname)) {
    throw new CollectionError(400, 'platform_mismatch', 'Use a public YouTube channel or video link.');
  }
  if (url.hostname === 'youtu.be') {
    if (!/^\/[A-Za-z0-9_-]{11}$/.test(url.pathname)) throw new CollectionError(400, 'unsupported_youtube_url', 'Use a channel link or one public video link.');
  } else if (!( /^\/@[^/]+(?:\/videos)?\/?$/.test(url.pathname) || /^\/channel\/UC[A-Za-z0-9_-]+(?:\/videos)?\/?$/.test(url.pathname) ||
    (url.pathname === '/watch' && /^[A-Za-z0-9_-]{11}$/.test(url.searchParams.get('v') || '')) || /^\/shorts\/[A-Za-z0-9_-]{11}$/.test(url.pathname))) {
    throw new CollectionError(400, 'unsupported_youtube_url', 'Use a public YouTube channel or video link. Search and playlist scraping are not enabled.');
  }
  for (const key of [...url.searchParams.keys()]) if (key !== 'v') url.searchParams.delete(key);
  return {
    startUrls: [{ url: url.href }], maxResults: maxItems, maxResultsShorts: 0, maxResultStreams: 0,
    sortVideosBy: 'NEWEST', transcriptionAndSubtitle: 'ALWAYS_SUBTITLES', subtitlesLanguage: 'any', subtitlesFormat: 'srt',
    saveSubsToKVS: false, preferAutoGeneratedSubtitles: false, aiVideoDescription: false, aiVideoSummary: false,
  };
}

type Fetcher = typeof fetch;
async function apifyRequest(path: string, config: ApifyConfig, fetcher: Fetcher, init: RequestInit = {}): Promise<unknown> {
  const response = await fetcher('https://api.apify.com/v2/' + path, {
    ...init, redirect: 'error', signal: AbortSignal.timeout(12_000),
    headers: { authorization: 'Bearer ' + config.token, 'content-type': 'application/json', ...init.headers },
  });
  if (!response.ok) {
    await response.body?.cancel();
    throw new CollectionError(502, 'provider_error', 'The collection provider did not accept this request. No automatic retry was started.');
  }
  const text = await readTextLimited(response, 2 * 1024 * 1024);
  try { return JSON.parse(text); } catch { throw new CollectionError(502, 'provider_response_invalid', 'The collection provider returned an unreadable response.'); }
}

function object(value: unknown): Record<string, unknown> {
  return value && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : {};
}
function providerId(value: unknown): string {
  if (typeof value !== 'string' || !/^[A-Za-z0-9]{6,64}$/.test(value)) throw new CollectionError(502, 'provider_response_invalid', 'The collection provider returned an invalid job reference.');
  return value;
}

export async function startApify(source: Source, userId: string, env: Env, fetcher: Fetcher = fetch): Promise<{ status: 'running'; jobToken: string; message: string }> {
  const config = requireConfig(env, userId);
  const input = youtubeInput(source, config.maxItems);
  const params = new URLSearchParams({ build: config.build, timeout: '120', maxItems: String(config.maxItems), maxTotalChargeUsd: String(config.maxCharge), restartOnError: 'false', waitForFinish: '0' });
  const response = object(await apifyRequest('actors/' + YOUTUBE_ACTOR + '/runs?' + params, config, fetcher, { method: 'POST', body: JSON.stringify(input) }));
  const run = object(response.data);
  const runId = providerId(run.id), actorId = providerId(run.actId);
  const jobToken = await new SignJWT({ runId, actorId, source, maxItems: config.maxItems })
    .setProtectedHeader({ alg: 'HS256', typ: 'JWT' }).setSubject(userId).setIssuer('therecap-collection').setAudience('collection-job')
    .setIssuedAt().setExpirationTime('20m').sign(new TextEncoder().encode(config.secret));
  return { status: 'running', jobToken, message: 'Collecting up to ' + config.maxItems + ' recent videos and available captions. Missing captions will remain metadata only.' };
}

export function captionsText(value: unknown): string {
  if (!Array.isArray(value)) return '';
  for (const entry of value) {
    const subtitle = object(entry);
    // Only inline subtitle text is consumed. No provider-supplied URL is fetched.
    if (typeof subtitle.srt !== 'string') continue;
    const text = subtitle.srt.replace(/^\s*\d+\s*$/gm, '').replace(/^.*-->.*$/gm, '').replace(/^WEBVTT.*$/gm, '');
    const result = plainText(text);
    if (result) return result;
  }
  return '';
}

export function normalizeYouTubeItems(items: unknown, source: Source, maxItems = 5): SourceUpdate[] {
  if (!Array.isArray(items)) throw new CollectionError(502, 'provider_response_invalid', 'The collection provider returned an invalid dataset.');
  const updates = new Map<string, SourceUpdate>();
  for (const item of items) {
    const row = object(item);
    if (row.isMembersOnly === true || row.isPrivate === true) continue;
    const url = safeLink(row.url, 'https://www.youtube.com');
    if (!url || !['youtube.com', 'www.youtube.com', 'm.youtube.com', 'youtu.be'].includes(new URL(url).hostname) || updates.has(url)) continue;
    const transcript = captionsText(row.subtitles), description = plainText(row.text, 700);
    const date = typeof row.date === 'string' ? Date.parse(row.date) : NaN;
    const refs = Array.isArray(row.descriptionLinks) ? row.descriptionLinks : [];
    updates.set(url, {
      id: 'live-' + createHash('sha256').update(source.id + '\n' + url).digest('hex').slice(0, 24), sourceId: source.id, contributorIds: [],
      title: plainText(row.title, 240) || 'Untitled video', summary: transcript ? transcript.slice(0, 700) : description,
      ...(transcript ? { content: transcript, contentKind: 'transcript' as const } : { contentKind: 'metadata_only' as const }),
      url, publishedAt: Number.isFinite(date) ? new Date(date).toISOString() : '', format: 'video', topics: [], brands: [], sponsors: [],
      references: refs.slice(0, 10).flatMap((value) => {
        const ref = object(value), link = safeLink(ref.url, url);
        return link ? [{ title: plainText(ref.text, 160) || new URL(link).hostname, url: link }] : [];
      }),
      insights: [], ...(typeof row.duration === 'string' ? { duration: plainText(row.duration, 30) } : {}),
      ...(safeLink(row.thumbnailUrl, url) ? { image: safeLink(row.thumbnailUrl, url) } : {}), isSample: false,
      coverage: transcript ? 'Caption transcript collected; visual content and transcript completeness not verified; text capped at 24,000 characters' : 'Metadata only: video description; captions unavailable; video content not analyzed',
    });
    if (updates.size >= Math.min(maxItems, 5)) break;
  }
  return [...updates.values()];
}

export async function pollApify(jobToken: string, userId: string, env: Env, fetcher: Fetcher = fetch): Promise<{ status: string; message?: string; result?: CollectionResult }> {
  const config = requireConfig(env, userId);
  if (!jobToken || jobToken.length > 8000) throw new CollectionError(400, 'invalid_job', 'This collection job is missing or invalid.');
  let claims;
  try {
    claims = (await jwtVerify(jobToken, new TextEncoder().encode(config.secret), { algorithms: ['HS256'], issuer: 'therecap-collection', audience: 'collection-job', requiredClaims: ['sub', 'iat', 'exp'] })).payload;
  } catch { throw new CollectionError(403, 'invalid_job', 'This collection job expired or could not be verified.'); }
  if (claims.sub !== userId) throw new CollectionError(403, 'job_owner_mismatch', 'This collection job belongs to a different account.');
  const runId = providerId(claims.runId), actorId = providerId(claims.actorId);
  const source = object(claims.source) as unknown as Source;
  if (source.platform !== 'YouTube' || typeof source.id !== 'string' || !source.url) throw new CollectionError(403, 'invalid_job', 'This job has invalid source details.');
  const response = object(await apifyRequest('actor-runs/' + runId, config, fetcher));
  const run = object(response.data);
  if (run.id !== runId || run.actId !== actorId) throw new CollectionError(403, 'invalid_job', 'The provider job does not match this request.');
  if (['READY', 'RUNNING', 'TIMING-OUT', 'ABORTING'].includes(String(run.status))) return { status: 'running', message: 'Collection is still running.' };
  if (run.status !== 'SUCCEEDED') return { status: 'failed', message: 'The provider job stopped without a complete result. No automatic retry was started.' };
  const datasetId = providerId(run.defaultDatasetId);
  const maxItems = Math.min(config.maxItems, Number(claims.maxItems) || 1, 5);
  const items = await apifyRequest('datasets/' + datasetId + '/items?clean=true&format=json&limit=' + maxItems, config, fetcher);
  const updates = normalizeYouTubeItems(items, source, maxItems);
  return { status: 'completed', result: { source: { ...source, status: 'ready' }, updates, notice: 'Collected a bounded recent sample, not a complete channel history. Text is extracted source material, not an AI recap. Descriptions are not video-content coverage.' } };
}
